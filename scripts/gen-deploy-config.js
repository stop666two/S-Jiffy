'use strict';
// Generates every deployment config from the single source in
// scripts/lib/deploy-config.js:
//
//   netlify.toml  — Netlify (redirects + headers + build)
//   _headers      — Cloudflare Pages (same security headers)
//   _redirects    — Cloudflare Pages / Netlify classic redirects
//   vercel.json   — Vercel (redirects + headers)
//
// Hand-editing any of those four files is a bug: edit deploy-config.js and rerun.
// `node scripts/gen-deploy-config.js --check` fails when a file is out of date.

var fs = require('fs');
var path = require('path');
var cfg = require('./lib/deploy-config.js');

var ROOT = path.resolve(__dirname, '..');
var CHECK = process.argv.indexOf('--check') >= 0;

var BANNER = '<!-- generated by scripts/gen-deploy-config.js from scripts/lib/deploy-config.js — do not edit by hand -->';

// cacheControl 传 null 时不输出 Cache-Control：Cloudflare Pages 对同名响应头是「拼接」
// 而不是「覆盖」，给 /* 设一次就会和 /assets/* 的值拼在一起（no-cache 会赢），缓存策略失效。
function headerPairs(cacheControl) {
  var pairs = [];
  pairs.push(['X-Content-Type-Options', cfg.SECURITY_HEADERS['X-Content-Type-Options']]);
  pairs.push(['X-Frame-Options', cfg.SECURITY_HEADERS['X-Frame-Options']]);
  pairs.push(['Referrer-Policy', cfg.SECURITY_HEADERS['Referrer-Policy']]);
  pairs.push(['Content-Security-Policy', cfg.CSP]);
  if (cacheControl) pairs.push(['Cache-Control', cacheControl]);
  return pairs;
}

function genNetlify() {
  var out = [];
  out.push('# generated by scripts/gen-deploy-config.js from scripts/lib/deploy-config.js');
  out.push('# Edit that module and rerun the generator; hand edits here are overwritten.');
  out.push('');
  cfg.REDIRECTS.forEach(function (p) {
    out.push('[[redirects]]');
    out.push('  from = "' + p[0] + '/*"');
    out.push('  to = "' + p[1] + '"');
    out.push('  status = 301');
    out.push('');
  });
  out.push('[build]');
  out.push('  command = ""');
  out.push('  publish = "."');
  out.push('');
  out.push('[[headers]]');
  out.push('  for = "/*"');
  out.push('  [headers.values]');
  headerPairs('no-cache').forEach(function (kv) {
    out.push('    ' + kv[0] + ' = "' + kv[1] + '"');
  });
  out.push('');
  out.push('[[headers]]');
  out.push('  for = "/assets/*"');
  out.push('  [headers.values]');
  out.push('    Cache-Control = "' + cfg.CACHE_RULES[0].value + '"');
  out.push('');
  return out.join('\n');
}

function genHeaders() {
  var out = [];
  out.push('# generated by scripts/gen-deploy-config.js from scripts/lib/deploy-config.js');
  out.push('# Cloudflare Pages reads this file; GitHub Pages ignores it.');
  out.push('');
  out.push('/*');
  headerPairs(null).forEach(function (kv) { out.push('  ' + kv[0] + ': ' + kv[1]); });
  out.push('');
  out.push('/assets/*');
  out.push('  Cache-Control: ' + cfg.CACHE_RULES[0].value);
  out.push('');
  return out.join('\n');
}

function genRedirects() {
  var out = [];
  out.push('# generated by scripts/gen-deploy-config.js from scripts/lib/deploy-config.js');
  out.push('# Cloudflare Pages / Netlify: old merged-tool URLs -> canonical URLs (301).');
  out.push('');
  cfg.REDIRECTS.forEach(function (p) {
    out.push(p[0] + '/*  ' + p[1] + '  301');
  });
  out.push('');
  return out.join('\n');
}

function genVercel() {
  var redirects = [];
  cfg.REDIRECTS.forEach(function (p) {
    redirects.push({ source: p[0], destination: p[1], permanent: true });
    redirects.push({ source: p[0] + '/:path*', destination: p[1], permanent: true });
  });
  var json = {
    $schema: 'https://openapi.vercel.sh/vercel.json',
    buildCommand: '',
    outputDirectory: '.',
    trailingSlash: true,
    redirects: redirects,
    headers: [
      { source: '/(.*)', headers: headerPairs(null).map(function (kv) { return { key: kv[0], value: kv[1] }; }) },
      { source: '/assets/(.*)', headers: [{ key: 'Cache-Control', value: cfg.CACHE_RULES[0].value }] }
    ]
  };
  return JSON.stringify(json, null, 2) + '\n';
}

var OUT = [
  ['netlify.toml', genNetlify()],
  ['_headers', genHeaders()],
  ['_redirects', genRedirects()],
  ['vercel.json', genVercel()]
];

var stale = [];
OUT.forEach(function (item) {
  var target = path.join(ROOT, item[0]);
  var current = null;
  try { current = fs.readFileSync(target, 'utf8'); } catch (e) { current = null; }
  if (current === item[1]) return;
  stale.push(item[0]);
  if (!CHECK) fs.writeFileSync(target, item[1]);
});

if (CHECK) {
  if (stale.length) {
    console.error('stale deploy config: ' + stale.join(', ') + ' — run node scripts/gen-deploy-config.js');
    process.exit(1);
  }
  console.log('deploy config up to date (' + cfg.REDIRECTS.length + ' redirects)');
  process.exit(0);
}
console.log(stale.length ? 'regenerated: ' + stale.join(', ') : 'deploy config already up to date');
