'use strict';
// Generates the static SEO/metadata surface:
//
//   - <meta name="description">, <link rel="canonical">, Open Graph tags per page
//   - sitemap.xml (home + every tool)
//   - robots.txt
//   - 404.html
//
// Why: before this, only 2 of 549 pages had a static description (the rest were
// injected by JavaScript, which crawlers that do not run JS never see), no page
// had a canonical URL, and there was no sitemap/robots/404 at all.
//
// The injected block is delimited by <!-- seo:start --> … <!-- seo:end --> so the
// generator is idempotent and never touches hand-written markup.
//
// Usage:
//   node scripts/gen-meta.js            # rewrite
//   node scripts/gen-meta.js --check    # exit 1 when any page is stale

var fs = require('fs');
var path = require('path');
var registry = require('./lib/registry.js');
var site = require('./lib/site.js');

var ROOT = registry.ROOT;
var CHECK = process.argv.indexOf('--check') >= 0;
var START = '<!-- seo:start (generated by scripts/gen-meta.js) -->';
var END = '<!-- seo:end -->';

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function block(opts) {
  var lines = [START];
  lines.push('  <meta name="description" content="' + esc(opts.description) + '">');
  lines.push('  <link rel="canonical" href="' + esc(opts.url) + '">');
  lines.push('  <meta property="og:type" content="website">');
  lines.push('  <meta property="og:site_name" content="S-Jiffy">');
  lines.push('  <meta property="og:title" content="' + esc(opts.title) + '">');
  lines.push('  <meta property="og:description" content="' + esc(opts.description) + '">');
  lines.push('  <meta property="og:url" content="' + esc(opts.url) + '">');
  lines.push('  <meta name="twitter:card" content="summary">');
  lines.push(END);
  return lines.join('\n');
}

/** 把 seo 区块写进页面：已有标记则替换，否则插到 </head> 之前。 */
function inject(html, blockText) {
  var nl = html.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
  var text = blockText.split('\n').join(nl);
  var s = html.indexOf(START);
  if (s >= 0) {
    var e = html.indexOf(END, s);
    if (e < 0) throw new Error('unterminated seo block');
    return html.slice(0, s) + text + html.slice(e + END.length);
  }
  var head = html.indexOf('</head>');
  if (head < 0) throw new Error('no </head>');
  return html.slice(0, head) + text + nl + html.slice(head);
}

var tools = registry.readRegistry(ROOT);
var stale = [];
var written = 0;

function pageFor(file, opts) {
  var raw = fs.readFileSync(file, 'utf8');
  var next = inject(raw, block(opts));
  if (next === raw) return;
  stale.push(path.relative(ROOT, file).split(path.sep).join('/'));
  if (!CHECK) { fs.writeFileSync(file, next); written++; }
}

// 首页
var toolList = tools.map(function (t) { return t.name; }).slice(0, 12).join('、');
pageFor(path.join(ROOT, 'index.html'), {
  title: 'S-Jiffy · 即用即走工具集',
  description: '549 个即用即走的在线工具，覆盖编解码、加密哈希、文本处理、颜色、数学、网络、代码生成、DevOps、图片与音频等 36 个分类。无登录、无广告，全部在浏览器本地完成，例如' + toolList + '。',
  url: site.SITE_ORIGIN + '/'
});

// 工具页
tools.forEach(function (t) {
  var file = path.join(ROOT, 'projects', t.slug, 'index.html');
  if (!fs.existsSync(file)) return;
  pageFor(file, {
    title: t.name + ' - S-Jiffy',
    description: t.desc,
    url: site.SITE_ORIGIN + '/' + t.link
  });
});

// sitemap.xml
var today = new Date().toISOString().slice(0, 10);
var sm = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'];
sm.push('  <url><loc>' + site.SITE_ORIGIN + '/</loc><lastmod>' + today + '</lastmod><changefreq>weekly</changefreq><priority>1.0</priority></url>');
tools.forEach(function (t) {
  sm.push('  <url><loc>' + site.SITE_ORIGIN + '/' + t.link + '</loc><lastmod>' + today + '</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>');
});
sm.push('</urlset>', '');
var smText = sm.join('\n');

// robots.txt
var robots = [
  'User-agent: *',
  'Allow: /',
  '',
  'Sitemap: ' + site.SITE_ORIGIN + '/sitemap.xml',
  ''
].join('\n');

// 404.html（Netlify / Cloudflare Pages / GitHub Pages 都按文件名识别）
var notFound = [
  '<!DOCTYPE html>',
  '<html lang="zh-CN">',
  '<head>',
  '  <meta charset="UTF-8">',
  '  <meta name="viewport" content="width=device-width, initial-scale=1.0">',
  '  <meta name="robots" content="noindex">',
  '  <title>404 · 页面不存在 - S-Jiffy</title>',
  '  <link rel="icon" type="image/svg+xml" href="/favicon.svg">',
  '  <link rel="stylesheet" href="/assets/css/global.css">',
  '</head>',
  '<body>',
  '  <main class="tool-workspace" style="text-align:center;padding-top:var(--space-6);">',
  '    <h1 style="font-size:48px;margin-bottom:var(--space-2);">404</h1>',
  '    <p class="tool-desc" style="margin-bottom:var(--space-4);">这个地址没有对应的工具。工具可能已被合并到功能更全的页面，或链接输错了。</p>',
  '    <p><a class="btn btn-primary" href="/">返回首页</a></p>',
  '    <p style="margin-top:var(--space-4);font-size:var(--font-size-sm);color:var(--color-text-secondary);">',
  '      常用入口：<a href="/projects/base64/">Base64</a> ·',
  '      <a href="/projects/json-formatter/">JSON 格式化</a> ·',
  '      <a href="/projects/hash-generator/">哈希计算</a> ·',
  '      <a href="/projects/password-generator/">密码生成</a> ·',
  '      <a href="/projects/timestamp-converter/">时间戳转换</a>',
  '    </p>',
  '  </main>',
  '</body>',
  '</html>',
  ''
].join('\n');

[['sitemap.xml', smText], ['robots.txt', robots], ['404.html', notFound]].forEach(function (item) {
  var file = path.join(ROOT, item[0]);
  var current = null;
  try { current = fs.readFileSync(file, 'utf8'); } catch (e) { current = null; }
  if (current === item[1]) return;
  stale.push(item[0]);
  if (!CHECK) { fs.writeFileSync(file, item[1]); written++; }
});

if (CHECK) {
  if (stale.length) {
    console.error('stale SEO output (' + stale.length + '): ' + stale.slice(0, 5).join(', ') + (stale.length > 5 ? ' …' : ''));
    console.error('run node scripts/gen-meta.js');
    process.exit(1);
  }
  console.log('SEO output up to date (' + tools.length + ' tools + home, sitemap, robots, 404)');
  process.exit(0);
}
console.log(written ? 'updated ' + written + ' file(s)' : 'SEO output already up to date');
